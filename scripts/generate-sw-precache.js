/**
 * Generate sw-precache.js: precache URL list + content-hash CACHE_VERSION.
 * Run after adding/renaming app shell files: npm run build:sw
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const ROOT_FILES = [
  "index.html",
  "styles.css",
  "script.js",
  "manifest.webmanifest",
];


function walkFiles(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) {
      walkFiles(full, out);
    } else if (st.isFile()) {
      out.push(full);
    }
  }
  return out;
}

function toUrl(absPath) {
  const rel = path.relative(root, absPath).split(path.sep).join("/");
  return `./${rel}`;
}

const entries = [];

for (const name of ROOT_FILES) {
  const full = path.join(root, name);
  if (statSync(full, { throwIfNoEntry: false })?.isFile()) {
    entries.push(full);
  }
}

const iconsDir = path.join(root, "icons");
if (statSync(iconsDir, { throwIfNoEntry: false })?.isDirectory()) {
  walkFiles(iconsDir, entries);
}

const srcDir = path.join(root, "src");
walkFiles(srcDir, entries);

// Stable order; skip generated precache itself if ever listed
const unique = [...new Set(entries)]
  .filter((p) => path.basename(p) !== "sw-precache.js")
  .sort((a, b) => toUrl(a).localeCompare(toUrl(b)));

const hash = createHash("sha256");
for (const file of unique) {
  hash.update(toUrl(file));
  hash.update("\0");
  hash.update(readFileSync(file));
  hash.update("\0");
}
const version = hash.digest("hex").slice(0, 16);

const urls = unique.map(toUrl);
const outPath = path.join(root, "sw-precache.js");
const body = `/* Generated by scripts/generate-sw-precache.js — do not edit by hand.
 * Re-run: npm run build:sw
 */
self.__CACHE_VERSION = ${JSON.stringify(version)};
self.__PRECACHE = ${JSON.stringify(urls, null, 2)};
`;

writeFileSync(outPath, body, "utf8");
console.log(`Wrote ${path.relative(root, outPath)} (${urls.length} urls, version ${version})`);
